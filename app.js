// Helper: Generar y ordenar variables SHAP por magnitud absoluta
function getShapItemsForStep(shapObj) {
  const definitions = [
    { key: 'oni', name: 'ONI (Forzante ENSO)', desc: 'Contribución SHAP del ONI' },
    { key: 'gwetroot', name: 'Humedad Radicular (SMAP)', desc: 'Contribución SHAP Humedad Radicular' },
    { key: 'precip', name: 'Lluvia Mensual (GPM)', desc: 'Contribución SHAP Lluvia' },
    { key: 'ndvi', name: 'Vigor Vegetativo (MODIS)', desc: 'Contribución SHAP NDVI' },
    { key: 't2mMax', name: 'Temperatura Máx (MERRA)', desc: 'Contribución SHAP Temperatura' }
  ];

  const items = definitions.map(d => {
    const val = Number(shapObj[d.key] != null ? shapObj[d.key] : 0);
    const pushesDrought = val >= 0;
    return {
      key: d.key,
      name: d.name,
      label: `${d.name} [${pushesDrought ? '+ Sequía' : '- Sequía'}]`,
      signLabel: pushesDrought ? `▲ ${d.name}` : `▼ ${d.name}`,
      value: val,
      absVal: Math.abs(val),
      color: pushesDrought ? '#EF4444' : '#10B981',
      desc: d.desc,
      pushesDrought: pushesDrought
    };
  });

  // Ordenar de mayor a menor contribución absoluta
  items.sort((a, b) => b.absVal - a.absVal);
  return items;
}

