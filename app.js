      shapText.innerHTML = `👉 El pulso torrencial de <b class="text-blue-300">Lluvia (+${currentStepData.shap.precip.toFixed(2)})</b> sobre planicies sedimentarias de baja pendiente dispara el anegamiento transfronterizo.`;
